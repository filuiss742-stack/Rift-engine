package com.rift.engine.input

/**
 * Platform-independent identifiers for the keyboard keys currently supported
 * by the engine adapters. Bind them to game-owned named actions with
 * [InputActionMap]; this list is intentionally small and is not exhaustive.
 */
object EngineKey {
    const val A = 1
    const val D = 2
    const val W = 3
    const val S = 4

    const val LEFT = 5
    const val RIGHT = 6
    const val UP = 7
    const val DOWN = 8

    const val SPACE = 9
    const val ENTER = 10
    const val ESCAPE = 11
    const val TAB = 12
    const val E = 13
    const val Q = 14
    const val F = 15
    const val R = 16
    const val SHIFT = 17
    const val CTRL = 18
    const val ALT = 19
}
